#!/usr/bin/env python
"""
Emit `Conference/paper/results.json` from the measured artefacts.

The paper's Section 5 quotes numbers. Hand-copying them is how the previous
draft ended up claiming 0.120 where the artefact said 0.119, and 0.572 where
the artefact said 0.568. This script makes every number in the paper traceable
to a file and regenerable with one command.

    python scripts/emit_paper_results.py
"""

import json
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Conference", "paper", "results.json")

AUTHOR = {                      # reproduced by the authors' extract_metrics.py
    "RT-f1_0_start": (66.56, 0.75),
    "RT-f1_0_end": (67.49, 2.24),
    "RT-f1_0_gap": (0.93, 1.58),
    "RT-avg_f1_t>0": (57.09, 2.33),
    "RT-recall_0": (27.50, 5.62),
    "final_precision": (31.01, 4.16),
    "final_auc": (64.00, 5.63),
}
AUTHOR_N = 5


def ms(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return None
    return {"mean": round(100 * sum(xs) / len(xs), 2),
            "std": round(100 * st.stdev(xs), 2) if len(xs) > 1 else 0.0,
            "n": len(xs)}


def metrics(rec):
    pt = rec.get("per_trial", [])
    out = {"n": len(pt), "rounds": rec.get("n_rounds"),
           "source": os.path.relpath(rec.get("_path", ""), ROOT)
           if rec.get("_path") else None}
    series = {
        "RT-f1_0_start": lambda t: t["round0"]["f1_initial"],
        "RT-f1_0_end": lambda t: t["rounds"][-1]["f1_round0_nodes"],
        "RT-avg_f1_t>0": lambda t: (sum(r["f1_query"] for r in t["rounds"])
                                    / len(t["rounds"])),
        "RT-recall_0": lambda t: t["rounds"][-1]["recall_query"],
        "final_precision": lambda t: t["rounds"][-1].get("precision_query"),
        "final_auc": lambda t: t["rounds"][-1].get("auc_query"),
        "recall_at_p30": lambda t: t["rounds"][-1].get("recall_at_p30"),
        "recall_at_p50": lambda t: t["rounds"][-1].get("recall_at_p50"),
    }
    for k, fn in series.items():
        vals = []
        for t in pt:
            try:
                vals.append(fn(t))
            except (KeyError, IndexError, TypeError, ZeroDivisionError):
                pass
        out[k] = ms(vals)
    # round-0 forgetting: end minus start, per trial
    gaps = []
    for t in pt:
        try:
            gaps.append(t["rounds"][-1]["f1_round0_nodes"] - t["round0"]["f1_initial"])
        except (KeyError, IndexError):
            pass
    out["RT-f1_0_gap"] = ms(gaps)
    # worst per-round F1, to expose instability rather than hide it
    worst = []
    for t in pt:
        f = [r["f1_query"] for r in t.get("rounds", [])]
        if f:
            worst.append(min(f))
    out["worst_round_f1"] = ms(worst)
    return out


def main():
    names = sys.argv[1:] or ["fixed_masks_embed_3t", "fixed_masks_raw_3t",
                             "best_raw_3t"]
    payload = {
        "_comment": "Generated by scripts/emit_paper_results.py. Do not hand-edit; "
                    "regenerate instead. Every value traces to a file in reports/.",
        "author": {"source": "vendor/author-tpne/result/config_author_control",
                   "n": AUTHOR_N,
                   "metrics": {k: {"mean": v[0], "std": v[1]}
                               for k, v in AUTHOR.items()}},
        "ours": {},
    }
    for n in names:
        p = os.path.join(ROOT, "reports", f"{n}.json")
        if not os.path.exists(p):
            print(f"  skip {n}: not found", file=sys.stderr)
            continue
        rec = json.load(open(p))
        rec["_path"] = p
        payload["ours"][n] = metrics(rec)
        print(f"  {n}: f1_0={payload['ours'][n]['RT-f1_0_start']} "
              f"avg_f1={payload['ours'][n]['RT-avg_f1_t>0']} "
              f"recall={payload['ours'][n]['RT-recall_0']}", file=sys.stderr)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(payload, open(OUT, "w"), indent=1)
    print(f"wrote {os.path.relpath(OUT, ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()